def _make_table(items):

    source, key = items[0]

    #print("source ", source[key])
    #print("key ", key)

    rows_count = len(source["step"])
    cols_count = len(items)

    column_names = []
    for n in range(len(items)):
        source, key = items[n]
        key_name = str(key)
        key_name = key_name.replace("_mean", '')

        column_names.append(key_name)

    values = numpy.zeros((rows_count, cols_count))

    for n in range(len(items)):
        source, key = items[n]

        v = source[key]

        values[:, n] = v


    return column_names, values


def markdown_export_table(table_names, table_values, root, num_samples=32):
    """Export a readable Markdown EDA report with evenly sampled training rows."""

    root = os.path.abspath(root)
    output_dir = os.path.join(root, "eda")
    os.makedirs(output_dir, exist_ok=True)

    table_values = numpy.asarray(table_values, dtype=float)

    if table_values.ndim != 2:
        raise ValueError("table_values must be a 2D array.")

    if table_values.shape[1] != len(table_names):
        raise ValueError("Number of column names must match table_values.")

    if num_samples < 1:
        raise ValueError("num_samples must be at least 1.")

    num_rows = table_values.shape[0]

    if num_rows == 0:
        raise ValueError("Cannot export an empty training log.")

    # Select evenly spaced rows across the entire training run.
    # Always include the first and last rows when sampling multiple rows.
    if num_rows <= num_samples:
        sample_indices = numpy.arange(num_rows)
    elif num_samples == 1:
        sample_indices = numpy.array([num_rows - 1])
    else:
        sample_indices = numpy.linspace(
            0, num_rows - 1, num_samples
        ).round().astype(int)

    sampled_values = table_values[sample_indices]

    # Load experiment configuration.
    config_path = os.path.join(root, "config_params.json")

    with open(config_path, "r", encoding="utf-8") as f:
        config = json.load(f)

    # Find the training step column.
    step_idx = (
        table_names.index("step")
        if "step" in table_names
        else None
    )

    if step_idx is not None:
        total_steps = int(table_values[-1, step_idx])
    else:
        total_steps = num_rows

    lines = []

    # Report header.
    lines.extend([
        "# Drone Racing RL — Experiment Report",
        "",
        "## Experiment Overview",
        "",
        f"- **Training steps:** {total_steps:,}",
        f"- **Logged rows:** {num_rows:,}",
        f"- **Displayed samples:** {len(sample_indices):,}",
        "",
        "## Hyperparameters",
        "",
    ])

    # Readable configuration list instead of a large JSON dump.
    for key, value in config.items():
        if isinstance(value, (dict, list)):
            value = json.dumps(value, ensure_ascii=False)
        lines.append(f"- **{key}:** `{value}`")

    lines.extend([
        "",
        "## Training Metrics",
        "",
        (
            f"Showing **{len(sample_indices)}** evenly spaced samples "
            f"from **{num_rows}** logged rows."
        ),
        "",
        "> Rows are sampled across the complete run, including the "
        "first and last logged rows when more than one sample is shown.",
        "",
    ])

    # Markdown table header.
    lines.append("| " + " | ".join(table_names) + " |")
    lines.append("| " + " | ".join(
        "---:" if name == "step" else "---:"
        for name in table_names
    ) + " |")

    # Only write sampled rows.
    for row in sampled_values:
        formatted = []

        for col_idx, value in enumerate(row):
            if not numpy.isfinite(value):
                formatted.append("—")
            elif table_names[col_idx] == "step":
                formatted.append(f"{int(value):,}")
            else:
                formatted.append(f"{value:.4f}")

        lines.append("| " + " | ".join(formatted) + " |")

    lines.extend([
        "",
        "---",
        "",
        "*Generated by the drone racing RL EDA pipeline.*",
        "",
    ])

    output_path = os.path.join(output_dir, "result.md")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"EDA report saved to: {output_path}")



def run_drone_eda(experiment_root_path, sample_count=32, skip_first_line=True):
    root = str(experiment_root_path)
    
    output_dir = root + "/eda"

    if not os.path.exists(output_dir):
        os.makedirs(output_dir)


    env_path    = root + "/env.jsonl"
    agent_path  = root + "/agent.jsonl"


    env     = load_jsonl(env_path, skip_first_line=skip_first_line)
    agent   = load_jsonl(agent_path, skip_first_line=skip_first_line)

    

    fig, ax = plt.subplots(2, figsize=(9, 5))
    plot_value_line(ax[0], env, "gates_passed_ratio", "royalblue")
    plot_value_line(ax[1], env, "success_lap", "red")
    save_plot(fig, output_dir + "/env_success_rate.png")

    fig, ax = plt.subplots(2, figsize=(9, 5))
    plot_value_line(ax[0], env, "speed_mean", "royalblue")
    plot_value_line(ax[0], env, "speed_max", "red")
    ax[0].legend()
    plot_value_line(ax[1], env, "g_force_mean", "royalblue")
    plot_value_line(ax[1], env, "g_force_max", "red")
    ax[1].legend()
    save_plot(fig, output_dir + "/env_speed_force.png")


    fig, ax = plt.subplots(figsize=(9, 5))
    plot_value_line(ax, env, "episode_done_crash", "red")
    plot_value_line(ax, env, "episode_done_time", "royalblue")
    ax.legend()
    save_plot(fig, output_dir + "/env_done_rate.png")


    fig, ax = plt.subplots(3, figsize=(9, 5))
    plot_value_line(ax[0], agent, "loss_actor", "red")
    plot_value_line(ax[1], agent, "loss_critic", "royalblue")
    plot_value_line(ax[2], agent, "loss_entropy", "green")
    save_plot(fig, output_dir + "/agent_loss.png")


    fig, ax = plt.subplots(2, figsize=(9, 5))
    plot_value_line(ax[0], agent, "actions_mag", "red")
    plot_value_line(ax[1], agent, "actions_std", "royalblue")
    save_plot(fig, output_dir + "/agent_actions_mu_var.png")

    fig, ax = plt.subplots(2, figsize=(9, 5))
    plot_value_line(ax[0], agent, "actions_saturation_ratio", "red")
    plot_value_line(ax[1], agent, "action_delta_mean", "royalblue")
    save_plot(fig, output_dir + "/agent_actions_saturation_stability.png")

    items = []
    items.append((env, "step")) 
    items.append((env, "gates_passed_ratio_mean"))
    items.append((env, "success_lap_mean"))
    items.append((env, "speed_mean_mean"))
    items.append((env, "speed_max_mean"))
    items.append((env, "g_force_mean_mean"))
    items.append((env, "g_force_max_mean"))
    items.append((env, "episode_done_crash_mean"))
    items.append((env, "episode_done_time_mean"))
    items.append((agent, "actions_mag_mean"))
    items.append((agent, "actions_std"))
    items.append((agent, "actions_saturation_ratio"))
    items.append((agent, "action_delta_mean"))


    table_names, table_values = _make_table(items)

    markdown_export_table(table_names, table_values, root, 32)
    